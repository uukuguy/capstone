"""Resolve the isolated analysis environment; no runtime installation or Provider use."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    manifest_path = root / 'configs/runtime/native-analysis.json'
    manifest = json.loads(manifest_path.read_text())
    constraints_path = root / manifest['constraints_source']
    constraints = json.loads(constraints_path.read_text())['dependencies']
    output = args.output or root / 'configs/runtime/native-analysis.lock.txt'
    with tempfile.TemporaryDirectory() as temporary:
        directory = Path(temporary)
        source, pins, lock = (directory / name for name in ('requirements.in', 'constraints.txt', 'resolved.txt'))
        source.write_text('\n'.join(item['requirement'] for item in manifest['packages']) + '\n')
        pins.write_text(''.join(f'{name}=={version}\n' for name, version in sorted(constraints.items())))
        subprocess.run(['uv', 'pip', 'compile', str(source), '--constraints', str(pins),
            '--python-version', manifest['python_version'], '--universal', '--only-binary', ':all:',
            '--generate-hashes', '--no-annotate', '--no-header', '--output-file', str(lock)], check=True)
        header = ('# Generated by python tools/lock_native_analysis.py; do not edit resolved versions.\n'
                  '# manifest-sha256: ' + hashlib.sha256(manifest_path.read_bytes()).hexdigest() + '\n'
                  '# shared-constraints-sha256: ' + hashlib.sha256(constraints_path.read_bytes()).hexdigest() + '\n')
        output.write_text(header + lock.read_text())


if __name__ == '__main__':
    main()
